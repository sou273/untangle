@dataclass
class EvalResult:
    total: int
    leaks: list[tuple[str, str]]         # (文の番号, Gemini まで届いてしまった語)
    stopped: list[tuple[str, str]]       # 残っていたが消し残し検査で保留になり、届かなかった語
    over: list[tuple[str, str]]          # (文の番号, 消えてしまった判断に要る語)
    held: int                            # 消し残し検査で保留になった数
    rows: list[dict] = field(default_factory=list)  # 文ごとの結果（伏せた後の形・漏れ・消しすぎ）

    @property
    def leak_count(self) -> int:
        return len(self.leaks)


def evaluate(masker: Masker, cases=None, workers: int = 1) -> EvalResult:
    cases = CASES if cases is None else cases

    def one(c):
        text, secrets, needed = c
        return c, masker.mask(text)

    with ThreadPoolExecutor(max_workers=workers) as ex:
        done = list(ex.map(one, cases))
    leaks, stopped, over, held, rows = [], [], [], 0, []
    for i, ((text, secrets, needed), r) in enumerate(done, 1):
        out = r.text or ""
        held += r.held
        row = {"no": i, "masked": r.text, "held": r.held, "held_reason": r.residual, "leaks": [], "over": []}
        for s in secrets:
            if s in out:
                (stopped if r.held else leaks).append((str(i), s))
                if not r.held:
                    row["leaks"].append(s)
        for n in needed:
            if n not in out:
                over.append((str(i), n))
                row["over"].append(n)
        rows.append(row)
    return EvalResult(len(cases), leaks, stopped, over, held, rows)
